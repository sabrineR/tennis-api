import { ApiProperty } from '@nestjs/swagger';

export class CountryResponseDto {
  @ApiProperty({ format: 'uri', example: 'https://tenisu.latelier.co/resources/Serbie.png' })
  picture!: string;

  @ApiProperty({ example: 'SRB' })
  code!: string;
}

export class PlayerDataResponseDto {
  @ApiProperty({ type: 'integer', example: 2 })
  rank!: number;

  @ApiProperty({ type: 'integer', example: 2542 })
  points!: number;

  @ApiProperty({ type: 'integer', example: 80000, description: 'Weight in grams.' })
  weight!: number;

  @ApiProperty({ type: 'integer', example: 188, description: 'Height in centimetres.' })
  height!: number;

  @ApiProperty({ type: 'integer', example: 31, description: 'Age in years.' })
  age!: number;

  @ApiProperty({ type: 'array', items: { type: 'integer', enum: [0, 1] }, example: [1, 1, 1, 1, 1] })
  last!: (0 | 1)[];
}

export class PlayerResponseDto {
  @ApiProperty({ type: 'integer', minimum: 1, example: 52, description: 'ID generated by PostgreSQL.' })
  id!: number;

  @ApiProperty({ example: 'Novak' })
  firstname!: string;

  @ApiProperty({ example: 'Djokovic' })
  lastname!: string;

  @ApiProperty({ example: 'N.DJO' })
  shortname!: string;

  @ApiProperty({ enum: ['M', 'F'], example: 'M' })
  sex!: 'M' | 'F';

  @ApiProperty({ type: () => CountryResponseDto })
  country!: CountryResponseDto;

  @ApiProperty({ format: 'uri', example: 'https://tenisu.latelier.co/resources/Djokovic.png' })
  picture!: string;

  @ApiProperty({ type: () => PlayerDataResponseDto })
  data!: PlayerDataResponseDto;
}

export class PlayersResponseDto {
  @ApiProperty({ type: () => [PlayerResponseDto], description: 'Players ordered by rank ASC, then id ASC. Empty array when no players exist.' })
  players!: PlayerResponseDto[];
}
